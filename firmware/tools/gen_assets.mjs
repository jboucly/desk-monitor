#!/usr/bin/env node
// Generates the LVGL fonts and the icon tables shared by the firmware and the web editor.
//
// Inputs:  protocol/icons.json (icon names), Inter + Material Design Icons (downloaded with `npm pack`).
// Outputs: firmware/core/src/fonts/*.c, firmware/core/src/generated/icons.inc, web/src/generated/icons.ts
//
// Usage:   node firmware/tools/gen_assets.mjs   (needs network access and npx)

import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const FONTS_OUT = join(ROOT, 'firmware/core/src/fonts');
const GEN_OUT = join(ROOT, 'firmware/core/src/generated');
const WEB_OUT = join(ROOT, 'web/src/generated');

const MDI_PKG = '@mdi/font@7.4.47';
const INTER_PKG = '@fontsource/inter@5.3.0';
const LV_FONT_CONV = 'lv_font_conv@1.5.3';

// Latin-1 (French accents, °, «»), plus typographic quotes, dashes, ellipsis, bullet, euro sign
const TEXT_RANGE = '0x20-0x7E,0xA0-0xFF,0x2013-0x2014,0x2018-0x201E,0x2022,0x2026,0x20AC';
// Big numerals only need digits and a few signs
const DIGITS_RANGE = '0x20,0x25,0x2B-0x2E,0x30-0x3A,0x43,0x46,0xB0';

// Text fonts: [name, weight, size, range]
const TEXT_FONTS = [
  ['dm_font_14', 400, 14, TEXT_RANGE],
  ['dm_font_16', 500, 16, TEXT_RANGE],
  ['dm_font_20', 500, 20, TEXT_RANGE],
  ['dm_font_28', 600, 28, TEXT_RANGE],
  ['dm_font_40', 300, 40, TEXT_RANGE],
  ['dm_font_72', 300, 72, DIGITS_RANGE],
];

// Icon fonts: [name, size, filter]. The 72 px font only holds the weather icons (big weather card).
const ICON_FONTS = [
  ['dm_icons_18', 18, () => true],
  ['dm_icons_24', 24, () => true],
  ['dm_icons_32', 32, () => true],
  ['dm_icons_48', 48, () => true],
  ['dm_icons_72', 72, (name) => name.startsWith('weather-')],
];

const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: ['ignore', 'pipe', 'inherit'], ...opts }).toString();

// Download the font packages into a temporary directory
const tmp = mkdtempSync(join(tmpdir(), 'dm-assets-'));
run('npm', ['pack', MDI_PKG, INTER_PKG, '--silent'], { cwd: tmp });
for (const tgz of readdirSync(tmp).filter((f) => f.endsWith('.tgz'))) {
  const dir = join(tmp, tgz.replace(/\.tgz$/, ''));
  mkdirSync(dir);
  run('tar', ['xzf', join(tmp, tgz), '-C', dir]);
}
const pkgDir = (prefix) => join(tmp, readdirSync(tmp).find((d) => d.startsWith(prefix) && !d.endsWith('.tgz')), 'package');
const mdiDir = pkgDir('mdi-font-');
const interDir = pkgDir('fontsource-inter-');

// Resolve icon codepoints from the MDI stylesheet
const css = readFileSync(join(mdiDir, 'css/materialdesignicons.css'), 'utf8');
const codepoints = new Map();
for (const m of css.matchAll(/\.mdi-([a-z0-9-]+)::before \{\s*content: "\\([0-9A-F]+)";/g)) {
  codepoints.set(m[1], parseInt(m[2], 16));
}
const names = JSON.parse(readFileSync(join(ROOT, 'protocol/icons.json'), 'utf8')).icons;
const icons = names.map((name) => {
  const cp = codepoints.get(name);
  if (cp === undefined) throw new Error(`Unknown MDI icon: ${name}`);
  return { name, cp };
});

mkdirSync(FONTS_OUT, { recursive: true });
mkdirSync(GEN_OUT, { recursive: true });
mkdirSync(WEB_OUT, { recursive: true });

const convert = (name, font, size, range) => {
  run('npx', ['--yes', LV_FONT_CONV,
    '--font', font, '--range', range,
    '--size', String(size), '--bpp', '4', '--format', 'lvgl', '--no-compress',
    '--lv-include', 'lvgl.h', '--lv-font-name', name,
    '-o', join(FONTS_OUT, `${name}.c`)]);
  console.log(`  ${name}.c`);
};

console.log('Fonts:');
for (const [name, weight, size, range] of TEXT_FONTS) {
  convert(name, join(interDir, `files/inter-latin-${weight}-normal.woff`), size, range);
}
for (const [name, size, filter] of ICON_FONTS) {
  const range = icons.filter((i) => filter(i.name)).map((i) => `0x${i.cp.toString(16)}`).join(',');
  convert(name, join(mdiDir, 'fonts/materialdesignicons-webfont.ttf'), size, range);
}

// UTF-8 encoding of a codepoint as a C string literal
const utf8 = (cp) => [...Buffer.from(String.fromCodePoint(cp), 'utf8')].map((b) => `\\x${b.toString(16).toUpperCase()}`).join('');

const header = '// Generated by firmware/tools/gen_assets.mjs from protocol/icons.json. Do not edit.\n';
writeFileSync(join(GEN_OUT, 'icons.inc'),
  header + icons.map((i) => `{"${i.name}", "${utf8(i.cp)}"},`).join('\n') + '\n');

writeFileSync(join(WEB_OUT, 'icons.ts'),
  header +
  `import {\n${icons.map((i) => `  ${camel(i.name)},`).join('\n')}\n} from '@mdi/js';\n\n` +
  '/**\n * @description SVG path of every icon compiled into the firmware, keyed by MDI name.\n */\n' +
  `export const ICONS: Record<string, string> = {\n${icons.map((i) => `  '${i.name}': ${camel(i.name)},`).join('\n')}\n};\n`);

console.log(`Icons: ${icons.length}`);

function camel(name) {
  return 'mdi' + name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
}
