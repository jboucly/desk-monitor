#!/usr/bin/env node
// Generates the 3D printer catalog tables shared by the firmware and the web editor.
//
// Input:   protocol/printers.json (drivers and models)
// Outputs: firmware/core/src/generated/printers.inc, web/src/generated/printers.ts
//
// Usage:   node firmware/tools/gen_printers.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const catalog = JSON.parse(readFileSync(join(ROOT, 'protocol/printers.json'), 'utf8'));

// Every model must name a known driver, and ids must be unique
const ids = new Set();
for (const model of catalog.models) {
  if (!catalog.drivers[model.driver]) throw new Error(`Unknown driver ${model.driver} for ${model.id}`);
  if (ids.has(model.id)) throw new Error(`Duplicate printer id ${model.id}`);
  ids.add(model.id);
}

const header = '// Generated by firmware/tools/gen_printers.mjs from protocol/printers.json. Do not edit.\n';
const c = (text) => JSON.stringify(text);

// Firmware: {id, brand, name, driver, default port}
writeFileSync(
  join(ROOT, 'firmware/core/src/generated/printers.inc'),
  header +
    catalog.models
      .map((m) => `{${c(m.id)}, ${c(m.brand)}, ${c(m.name)}, ${c(m.driver)}, ${catalog.drivers[m.driver].port}},`)
      .join('\n') +
    '\n',
);

// Web editor: the same catalog, typed
writeFileSync(
  join(ROOT, 'web/src/generated/printers.ts'),
  header +
    `
/**
 * @description Protocol driver of a family of printers.
 */
export interface PrinterDriver {
  label: string;
  port: number;
  caps: string[];
}

/**
 * @description A printer model the screen can follow.
 */
export interface PrinterModel {
  id: string;
  brand: string;
  name: string;
  driver: string;
  tested?: boolean;
}

export const PRINTER_DRIVERS: Record<string, PrinterDriver> = ${JSON.stringify(catalog.drivers, null, 2)};

export const PRINTER_MODELS: PrinterModel[] = ${JSON.stringify(catalog.models, null, 2)};
`,
);

console.log(`Printers: ${catalog.models.length} models, ${Object.keys(catalog.drivers).length} drivers`);
